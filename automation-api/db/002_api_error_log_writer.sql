-- Run once as SYSTEM/DBA after 001_api_error_log.sql succeeded.
-- SQL*Plus prompts for the password without echoing it; do not put passwords in this file.
WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT FAILURE
SET VERIFY OFF
ACCEPT audit_password CHAR PROMPT 'Mot de passe initial SPAT_API_AUDIT_WRITER: ' HIDE

CREATE USER SPAT_API_AUDIT_WRITER IDENTIFIED BY "&&audit_password" ACCOUNT UNLOCK;
UNDEFINE audit_password
GRANT CREATE SESSION TO SPAT_API_AUDIT_WRITER;
GRANT INSERT ON SPAT_CAPITAINERIE.SPATERP_API_ERROR_LOG TO SPAT_API_AUDIT_WRITER;

EXIT SUCCESS
