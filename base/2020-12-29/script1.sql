CREATE OR REPLACE FORCE VIEW CONTRAT_CHANTIER_LIB_COMPLET ("ID", "IDCHANTIER", "DESIGNATION", "MONTANT", "PRESTATAIRE", "ETAT", "IDTRAVAUX_CHANTIER", "NOM_CHANTIER", "DATYDEBUT_CHANTIER", "DATYFIN_CHANTIER", "MONTANT_CHANTIER", "AVANCEMENT_CHANTIER", "IDTIERS_CHANTIER", "ETAT_CHANTIER", "ID_PRESTATAIRE", "NOM_PRESTATAIRE", "DESCRIPTION_PRESTATAIRE", "NIF_PRESTATAIRE", "STAT_PRESTATAIRE", "CONTACT_PRESTATAIRE", "RESPONSABLE_PRESTATAIRE", "ADRESSE_PRESTATAIRE", "TYPE_PRESTATAIRE", "ETAT_PRESTATAIRE", "PROJET", "CODE_ETAB", "NOCONTRAT", "TVA") AS 
  SELECT
	cc."ID",cc."IDCHANTIER",cc."DESIGNATION",cc."MONTANT",cc."PRESTATAIRE",cc."ETAT",
	c2.IDTRAVAUX AS IDTRAVAUX_chantier ,
	c2.NOM AS NOM_chantier ,
	c2.DATYDEBUT AS DATYDEBUT_chantier ,
	c2.DATYFIN AS DATYFIN_chantier ,
	c2.MONTANT AS MONTANT_chantier,
	c2.AVANCEMENT AS AVANCEMENT_chantier,
	c2.IDTIERS AS IDTIERS_chantier,
	c2.ETAT AS ETAT_chantier,
	t2.ID AS ID_PRESTATAIRE ,
	t2.NOM AS NOM_PRESTATAIRE, 
	t2.DESCRIPTION AS DESCRIPTION_PRESTATAIRE, 
	t2.NIF AS NIF_PRESTATAIRE, 
	t2.STAT AS STAT_PRESTATAIRE, 
	t2.CONTACT AS  CONTACT_PRESTATAIRE, 
	t2.RESPONSABLE AS RESPONSABLE_PRESTATAIRE, 
	t2.ADRESSE AS ADRESSE_PRESTATAIRE, 
	t2."TYPE" AS TYPE_PRESTATAIRE, 
	t2.ETAT AS ETAT_PRESTATAIRE,
  cc.PROJET, cc.code_etab, cc.NOCONTRAT, cc.TVA
FROM
	CONTRAT_CHANTIER cc
JOIN CHANTIER c2 ON
	cc.IDCHANTIER = c2.ID
JOIN TIERS t2 ON
	cc.PRESTATAIRE = t2.ID;

