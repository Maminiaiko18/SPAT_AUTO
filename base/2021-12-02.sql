create  or replace view rubrique_activite_CA_details as
select fd.id,
       fd.RUBRIQUE       idrubrique,
       ra.DESIGNATION as rubriquelib,
       categorie,
       categorielib,
       cp.desce       as code_prest,
       fd.designation,
       cast(fd.montanttaux as number(32,3)) as montant,
       cast(fd.mois as number(10)) as mois,
       cast(fd.annee as number(10)) as annee,
       fc.type,
       fc.typelib,
       fc.tiers,
       fc.tierslib
from FACT_CLT_FILL_LIB_REST_TAXE fd
         left join rubrique_activite ra on ra.id = fd.rubrique
         left join code_prestation cp on cp.val = ra.categorie
         join factureclientmsum_lib fc on fc.id = fd.idmere
where fc.etat >= 11;

create or replace view rubrique_activite_CA as
select idrubrique,
       rubriquelib,
       categorie,
       categorielib,
       code_prest,
       designation,
       cast(sum(montant) as number(32,3)) as montant,
       cast(mois as number(10)) as mois,
       cast(annee as number(10))as annee,
       type,
       typelib
from rubrique_activite_CA_details ca
group by idrubrique, rubriquelib, categorie, categorielib, code_prest, designation, mois, annee, type, typelib;


