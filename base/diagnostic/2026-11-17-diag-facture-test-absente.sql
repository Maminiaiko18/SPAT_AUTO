-- 1. La facture existe-t-elle dans la table mere ?
SELECT ID, DESIGNATION, NUMEROOP, DATY, TIERS, ETAT, PROJET, CODE_ETABLISSEMENT
FROM FACTURE_FOURNISSEUR_MERE
WHERE ID = 'TEST-RECETTE-FF-001'
   OR UPPER(DESIGNATION) LIKE '%TEST-RECETTE-FF-001%'
   OR UPPER(NUMEROOP) LIKE '%TEST-RECETTE-FF-001%';

-- 2. Est-elle dans la vue utilisee par la liste et le formulaire ?
SELECT *
FROM FACTFOURN_MSUM_LIB
WHERE ID = 'TEST-RECETTE-FF-001'
   OR UPPER(DESIGNATION) LIKE '%TEST-RECETTE-FF-001%';

-- 3. Requete exacte de BordereauFF.getFactures()
SELECT COUNT(*) AS NB
FROM FACTURE_FOURNISSEUR_MERE
WHERE ID IN ('TEST-RECETTE-FF-001');
