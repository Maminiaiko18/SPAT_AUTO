-- 4. Le tiers de test
SELECT ID, NOM, ETAT, TYPE, COMPTEAUXFOURNISSEUR, COMPTEAUXCLIENT
FROM TIERS
WHERE ID = 'DEMO-SITE-TIERS-1'
   OR UPPER(NOM) LIKE '%DEMO-SITE-TIERS-1%';

-- 5. Lien bordereau <-> facture eventuel
SELECT L.ID AS IDLIAISON, L.IDBORDEREAU, L.IDOP, L.MONTANT,
       B.NUMERO, B.ETAT, B.TIERS AS TIERS_BED, B.IDFACTURES, B.TYPEBORDEREAU
FROM LIAISONBORDEREAUFF L
LEFT JOIN BORDEREAUFF B ON B.ID = L.IDBORDEREAU
WHERE L.IDOP = 'TEST-RECETTE-FF-001';

-- 6. BED dont IDFACTURES contient l'ID de test
SELECT ID, NUMERO, ETAT, TIERS, IDFACTURES, DATY, TYPEBORDEREAU
FROM BORDEREAUFF
WHERE IDFACTURES LIKE '%TEST-RECETTE-FF-001%';

-- 7. Coherence tiers : facture vs tiers choisi
SELECT f.ID AS IDFACTURE, f.TIERS AS TIERS_FACTURE, t.NOM AS NOM_TIERS_FACTURE
FROM FACTURE_FOURNISSEUR_MERE f
LEFT JOIN TIERS t ON t.ID = f.TIERS
WHERE f.ID = 'TEST-RECETTE-FF-001';
