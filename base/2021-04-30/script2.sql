create view LIAISONBORDEREAU_SUM_MONTANT as
select IDBORDEREAU, SUM(MONTANT) AS MONTANT
from LIAISONBORDEREAU_LIBCOMPLET
GROUP BY IDBORDEREAU
/



  CREATE  VIEW BORDEREAU_LIB_MONTANT (ID, DATY, NUMERO, DESIGNATION, ETAT, TIERS, MONTANT) AS
  SELECT bf.ID,
       bf.DATY,
       bf.NUMERO,
       bf.DESIGNATION,
       bf.ETAT,
       bf.TIERSLIB  as TIERS,
       NVL(MO.MONTANT, 0) as montant
FROM BORDEREAU_LIBCOMPLET BF
         LEFT JOIN LIAISONBORDEREAU_SUM_MONTANT MO ON MO.IDBORDEREAU = BF.ID;
		 
create view BORDEREAU_LIB_MONTANTC as
    select *from BORDEREAU_LIB_MONTANT where ETAT=1;
create view BORDEREAU_LIB_MONTANTV as
    select *from BORDEREAU_LIB_MONTANT where ETAT>=1;