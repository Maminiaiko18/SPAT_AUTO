CREATE OR REPLACE VIEW OCCUPATION_FACTURECLIENT AS
(
	SELECT
		o.*,
		rub.COMPTE, 
		COALESCE(rub.MONTANT/rub.DUREE, 0) AS pu,
		COALESCE(o.duree * rub.montant / rub.duree, 0) AS montanttotal,
		fc.ID AS idfacture, fc.etat AS etatfacture
	FROM OCCUPMATERIELNAVALLIBCOMPLET o
	LEFT JOIN RUBRIQUEFACTUREFOURNISSEUR rub ON o.IDNATUREOPERATION = rub.DESIGNATION 
	LEFT JOIN FACTURE_CLIENT_DETAIL fcd ON fcd.IDACTE = o.ID
	LEFT JOIN FACTURE_CLIENT fc ON fcd.IDFACTURE = fc.ID
)