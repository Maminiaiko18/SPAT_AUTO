CREATE or replace VIEW BORDEREAUFF_LIB_MONTANT
AS
SELECT bf.ID,
       bf.DATY,
       bf.NUMERO,
       bf.DESIGNATION,
       bf.ETAT,
       bf.TIERSLIB  as TIERS,
       NVL(MO.MONTANT, 0) as montant
FROM BORDEREAUFF_LIBCOMPLET BF
         LEFT JOIN LIAISONBORDEREAUFF_SUM_MONTANT MO ON MO.IDBORDEREAU = BF.ID;