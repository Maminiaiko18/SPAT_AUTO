CREATE OR REPLACE
FORCE VIEW POSTEDESTINATAIREEXTERNE AS
SELECT
	"ID",
	"QUAI",
	"INTERNE",
	"VALQUAIS",
	"DESCEQUAIS",
	"TYPEQUAIS",
	"PROFONDEUR",
	"TIRANT",
	"PAYSQUAIS",
	"VALPAYS",
	"DESCEPAYS",
	"VALTYPEQUAIS",
	"DESCETYPEQUAIS"
FROM
	postedestinatairelibcomplet
WHERE
	interne = 'Externe';

