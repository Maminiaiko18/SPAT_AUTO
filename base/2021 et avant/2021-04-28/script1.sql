  SELECT et.ID,
       et.DATY,
       et.IDFOURNISSEUR,
       et.NOMFOURNISSEUR,
       et.IDTVA,
       et.REMARQUE,
       et.DATEEMISSION,
       et.DESIGNATION,
       et.IDDEVISE,
       et.NUMFACT,
       et.DATYECHEANCE,
       et.ETAT,
       et.MONTANTPAYE,
       et.RESTE,
       et.ENTITE,
       et.MONTANTTTDEVISE,
       et.BUDGET,
       et.RETENUE,
       et.NUMID,
       et.TIERSLIB,
       et.TVA,
       et.MONTANT,
       et.MONTANTAVOIR,
       et.MONTANTADDITIF,
       et.MONTANTNET,
       et.MONTANTTVA,
       et.MONTANTTTC,
       et.MONTANTTOTALAPAYER,
       et.TYPE,
       et.CODE_ETABLISSEMENT,
       et.PROJET
FROM EtatFactureMontantDaty et
WHERE et.etat = 11
  and et.ID not in (select id1 from LIAISONINTRATABLE_OP_VISE);
