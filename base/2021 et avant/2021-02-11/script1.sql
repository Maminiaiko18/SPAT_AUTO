

CREATE OR REPLACE VIEW OCCUPATION_FACTURECLIENT1 AS
	(SELECT
		o.*,
		rub.COMPTE, 
		COALESCE(rub.MONTANT/rub.DUREE, 0) AS pu,
		COALESCE(o.duree * rub.montant / rub.duree, 0) AS montanttotal
	FROM OCCUPMATERIELNAVALLIBCOMPLET o
	LEFT JOIN RUBRIQUEFACTUREFOURNISSEUR rub ON o.IDNATUREOPERATION = rub.DESIGNATION);

CREATE OR REPLACE VIEW OCCUPATION_FACTURE_VALIDE AS
	(
		SELECT o.id, fc.id AS idfacture, fc.etat AS etatfacture FROM OCCUPATIONMATERIELNAVAL o 
		LEFT JOIN FACTURE_CLIENT_DETAIL fcd ON fcd.IDACTE = o.ID
		LEFT JOIN FACTURE_CLIENT fc ON fcd.IDFACTURE = fc.ID WHERE fc.etat >= 11
	);
