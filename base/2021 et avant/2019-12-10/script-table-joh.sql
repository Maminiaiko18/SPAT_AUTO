create table Details_Patrimoine (
	id varchar(50) PRIMARY KEY,
	idPatrimoine varchar(50) references Patrimoine(id),
	natureObjet varchar(250),
	surfaceOccupe varchar(200), 
	surfaceDisponible varchar(200)
);

create view detailspatrimoinelib as (
	select Details_Patrimoine.id, patrimoine.libelle as idPatrimoine, natureObjet, surfaceOccupe, surfaceDisponible from Details_Patrimoine
	join patrimoine on Details_Patrimoine.idPatrimoine = patrimoine.id
);

CREATE SEQUENCE seq_details_patrimoine
  MINVALUE 1
  MAXVALUE 999999999999999999999999999
  START WITH 1
  INCREMENT BY 1
  CACHE 20;
  

create or replace FUNCTION getseqdetailspatrimoine
  RETURN NUMBER IS
  retour NUMBER;
BEGIN
  SELECT seq_details_patrimoine.nextval INTO retour FROM dual;
  return retour;
END;




