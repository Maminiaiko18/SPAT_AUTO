
CREATE OR REPLACE FORCE VIEW ORDONNERPAYEMENT_N_PAYE
AS
   SELECT op.*
     FROM ORDONNERPAYEMENT_LIBETAT op
    WHERE     op.id NOT IN (SELECT jc.IDORDRE
                              FROM journalcaisse jc
                             WHERE jc.IDORDRE = op.id)
          AND op.ETAT >= 11;
CREATE OR REPLACE FORCE VIEW ORDONNERPAYEMENT_PAYE_LIB

AS
   SELECT op.*
     FROM ORDONNERPAYEMENT_LIBETAT op
          JOIN journalcaisse jc ON jc.IDORDRE = op.id
    WHERE jc.ETAT >= 11 AND op.ETAT >= 11;
	
	CREATE OR REPLACE FORCE VIEW ORDONNERPAYEMENT_ANNULE
AS
   SELECT *
     FROM ORDONNERPAYEMENT_LIBETAT
    WHERE etat = 0;
	
	CREATE OR REPLACE FORCE VIEW ORDONNERPAYEMENT_CREE
AS
   SELECT *
     FROM ORDONNERPAYEMENT_LIBETAT
    WHERE etat = 1;