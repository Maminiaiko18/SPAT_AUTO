
   CREATE SEQUENCE  SEQ_NAV  MINVALUE 1 MAXVALUE 999999999999999999999999999 INCREMENT BY 1 START WITH 1 NOCACHE  NOORDER  NOCYCLE ;
   
   create or replace FUNCTION getseqnavire
	  RETURN NUMBER IS
	  retour NUMBER;
	BEGIN
	  SELECT SEQ_NAV.nextval INTO retour FROM dual;
	  return retour;
	END;
 
