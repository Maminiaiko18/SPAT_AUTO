CREATE OR REPLACE
FORCE VIEW "SPAT_CAPITAINERIE"."MATERIELNAVALLIBCOMPLET" ("ID",
"DENOMINATION",
"DATE_AQUISITION",
"IDMARQUE",
"PUISSANCE",
"DETENTEUR",
"MAINTENANCE",
"IDTYPE_MATERIEL",
"IMMATRICULATION",
"ETAT",
"VALMARQUE",
"DESCEMARQUE",
"VALTYPEMATERIEL",
"DESCETYPEMATERIEL") AS
SELECT
	mat."ID",
	mat."DENOMINATION",
	mat."DATE_AQUISITION",
	mat."IDMARQUE",
	mat."PUISSANCE",
	mat."DETENTEUR",
	mat."MAINTENANCE",
	mat."IDTYPE_MATERIEL",
	mat."IMMATRICULATION",
	mat."ETAT",
	marque.VAL AS valmarque,
	marque.DESCE AS descemarque,
	typemat.val AS valtypemateriel,
	typemat.DESCE AS descetypemateriel
FROM
	MATERIEL_NAVAL mat
LEFT JOIN MARQUE_MATERIEL marque ON
	marque.id = mat.IDMARQUE
LEFT JOIN TYPE_MATERIEL typemat ON
	typemat.id = mat.IDTYPE_MATERIEL;