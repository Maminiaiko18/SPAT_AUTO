  CREATE OR REPLACE VIEW STATISTIQUEACTIVITE_MICTSL (MOIS, ANNEE, SOMME_PLEIN20_VIDE20_PLEIN40, IDTYPEACTIONCONTENEUR, IDTYPEACTIONCONTENEURLIB) AS
  SELECT EXTRACT (MONTH FROM DATY) AS mois,
            EXTRACT (YEAR FROM DATY) AS annee,
            SUM (PLEIN20PIEDS) + SUM (VIDE20PIEDS) + SUM (PLEIN40PIEDS) + SUM(VIDE40PIEDS)
               AS somme_plein20_vide20_plein40,
            IDTYPEACTIONCONTENEUR,
            IDTYPEACTIONCONTENEURLIB
       FROM STATISTIQUEACTIVITE_LIBCOMPLET
      WHERE TYPESAISIE = 'TSAI001' and etat>=11
   GROUP BY EXTRACT (MONTH FROM DATY),
            EXTRACT (YEAR FROM DATY),
            IDTYPEACTIONCONTENEUR,
            IDTYPEACTIONCONTENEURLIB;


CREATE OR REPLACE VIEW STATISTIQUEACTIVITE_NONMICTSL (MOIS, ANNEE, NOMBREUNITE, IDTYPEMANIPULATIONLIB, IDTYPEMANIPULATION) AS
select extract(month from DATY) as mois,
       extract(year from DATY)  as annee,
       sum(NOMBREUNITE)         as NOMBREUNITE,
       IDTYPEMANIPULATIONLIB,
       IDTYPEMANIPULATION
from STATISTIQUEACTIVITE_LIBCOMPLET
WHERE TYPESAISIE = 'TSAI002'
  and ETAT >= 11
GROUP BY extract(month from DATY), extract(year from DATY),
         IDTYPEMANIPULATIONLIB,
         IDTYPEMANIPULATION;