CREATE OR REPLACE  VIEW ETATFACTUREMONTANTDATYVISE 
 AS 
  SELECT et.*
FROM EtatFactureMontantDaty et
   left join (select op.ded_id,op.id2 from LIAISONINTRATABLE_OP_PARFACT_F op group by op.ded_id,op.id2) op on op.ded_id=et.id 
WHERE et.etat = 11 and op.id2 is null ;


CREATE OR REPLACE  VIEW PATRIMOINELIB_ANALYSE_SUP (ID, IDOBJET, IDTYPEPATRIMOINE, REMARQUE, ETAT, LIBELLE, DESCRIPTION, MONTANT, OCCUPANT, DEBUT_CONTRAT, FIN_CONTRAT, UTILISATION, NOMBRE,
SUPERFICIE_OCCUPEE,superficie,SUPERFICIE_DISPONIBLE) AS 
  (select AN.ID,AN.IDOBJET,AN.IDTYPEPATRIMOINE,AN.REMARQUE,AN.ETAT,AN.LIBELLE,AN.DESCRIPTION,AN.MONTANT,AN.OCCUPANT,AN.DEBUT_CONTRAT,AN.FIN_CONTRAT,AN.UTILISATION,AN.NOMBRE,
            CAST(nvl(pat.surfaceoccupe,0) AS NUMBER(10,2)) AS SUPERFICIE_OCCUPEE ,
            cast(nvl(pat.superficie,0)as number(10,2)) as superficie,
             CAST((nvl(PAT.SUPERFICIE,0)-nvl(pat.surfaceoccupe,0)) as number(10,2)) AS SUPERFICIE_DISPONIBLE
            from patrimoinelib_analyse AN
                JOIN Patrimoine_I PAT ON PAT.ID=AN.ID);

