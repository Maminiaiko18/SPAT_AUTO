   ) ;
   
 ALTER TABLE AVOIR ADD CONSTRAINT FK_AVOIR_TYPE
 	FOREIGN KEY (TYPE) 
 	REFERENCES TYPEAVOIR(ID);
 	
 CREATE SEQUENCE seq_AVOIR
  MINVALUE 1
  MAXVALUE 999999999999999999999999999
  START WITH 1
  INCREMENT BY 1
  CACHE 20;


CREATE OR REPLACE
FUNCTION GET_seq_AVOIR RETURN NUMBER IS retour NUMBER;
BEGIN
	SELECT
	seq_AVOIR.nextval
INTO
	retour
FROM
	dual;

RETURN retour;
END;

CREATE OR REPLACE
VIEW AVOIR_LIB AS
SELECT
	av.id,
	av.daty,
	fc.DESIGNATION AS idfacture,
	AV.montant,
	ta.val AS TYPE,
	AV.etat
FROM
	avoir av
LEFT JOIN FACTUREFOURNISSEUR fc ON
	fc.id = av.idfacture
LEFT JOIN typeavoir ta ON
	ta.id = av.type;