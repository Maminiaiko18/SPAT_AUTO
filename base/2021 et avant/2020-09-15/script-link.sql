  
  CREATE OR REPLACE FORCE VIEW "SPAT_CAPITAINERIE"."PLACEMENTLIBCOMPLET" ("ID", "ENTITE", "DATE_PLACEMENT", "DATE_ECHEANCE", "DUREE", "MONTANT", "TAUX", "ETAT", "NUMERO", "IDDETAILS", "IDMEREDETAILS", "MOIS", "MONTANT_TERME", "INTERET_RECEVOIR", "INTERET_NET", "IDENTITE", "IDBANQUE", "VALENTITE", "DESCEENTITE", "VALBANQUE", "DESCEBANQUE") AS 
  select
    plt."ID",plt."ENTITE",plt."DATE_PLACEMENT",plt."DATE_ECHEANCE",plt."DUREE",plt."MONTANT",plt."TAUX",plt."ETAT",plt."NUMERO",
    det.ID as iddetails, IDMERE as idmeredetails, MOIS, MONTANT_TERME, INTERET_RECEVOIR, INTERET_NET,
    lp.id as IDENTITE, b.id as IDBANQUE, lp.val as VALENTITE, lp.desce as DESCEENTITE, b.val as VALBANQUE, b.desce as DESCEBANQUE
from placement plt
    join DETAILSPLACEMENT det on plt.ID = det.IDMERE
    left join ENTITE lp on lp.id = plt.ENTITE
    left join BANQUE b on b.id = plt.banque;
	
	
	
	
