
 CREATE OR REPLACE VIEW ordonneravecjc as
   select op.*,
   		  jc.id AS idjournal,
   		  jc.ETAT  AS etatjournalcaisse
from JOURNALCAISSE jc
        right join ORDONNERPAYEMENT op on op.id = jc.IDORDRE
where op.ETAT >= 11 ;

CREATE   VIEW ORDONNERPAYEMENT_final (ID, DED_ID, DATY, MONTANT, REMARQUE, ETAT) AS 
  SELECT '-'             AS id,
       op.ded_id,
       max(op.daty)    AS daty,
       sum(op.montant) AS montant,
      op.idjournal         AS remarque,
       op.etatjournalcaisse
FROM ordonneravecjc op
GROUP BY op.ded_id, op.etat, op.idjournal, op.etatjournalcaisse;


CREATE OR REPLACE   VIEW ETATFACTUREATTENTEPAIEMENT (ID, DATY, IDFOURNISSEUR, NOMFOURNISSEUR, IDTVA, REMARQUE, DATEEMISSION, DESIGNATION, IDDEVISE, NUMFACT, DATYECHEANCE, ETAT, MONTANTPAYE, RESTE, ENTITE, MONTANTTTDEVISE, BUDGET, RETENUE, NUMID, TIERSLIB, TVA, MONTANT, MONTANTAVOIR, MONTANTADDITIF, MONTANTNET, MONTANTTVA, MONTANTTTC, MONTANTTOTALAPAYER, TYPE, CODE_ETABLISSEMENT, PROJET) AS 
  select e.*
  	
  from ETATFACTUREMONTANTDATY e
  join ORDONNERPAYEMENT_final P ON p.ded_id=e.id
 		WHERE p.remarque IS NULL ;
 	
