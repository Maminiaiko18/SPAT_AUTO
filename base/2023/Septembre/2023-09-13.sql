	
		
		create table prioritaire(
    ID varchar2(100) constraint pk_prioritaire primary key ,
    IDROLE varchar2(100) constraint fk_prioRole references ROLES(IDROLE),
    REFUSER NUMBER constraint fk_prioRef references UTILISATEUR(REFUSER),
    RANG number(10),
    ETAT number(10)
);




CREATE SEQUENCE seqprioritaire
INCREMENT BY 1 
MINVALUE 1
 MAXVALUE 999999999999
 NOCYCLE CACHE 20 NOORDER; 

CREATE OR REPLACE FUNCTION getseqprioritaire
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT seqprioritaire.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;






