CREATE OR REPLACE VIEW PRIORITAIRELIB
AS
SELECT
	p.ID,
	p.IDROLE,
	p.REFUSER,
	p.RANG,
	p.ETAT,
	CASE
		WHEN p.ETAT = 1 THEN 'CREE'
		WHEN p.ETAT = 11 THEN 'VISE'
		END AS ETATLIB,
	CASE
		WHEN p.RANG  = 1 THEN 'OUI'
		WHEN p.RANG = 0 THEN 'NON'
		END AS RANGLIB,
u.NOMUSER AS utilisateur,
		r.DESCROLE AS roles
	FROM
		PRIORITAIRE p
	LEFT JOIN UTILISATEUR u ON
		u.REFUSER = p.REFUSER
	LEFT JOIN ROLES r ON
		r.IDROLE = p.IDROLE ;
		
		
		
		
		
		

