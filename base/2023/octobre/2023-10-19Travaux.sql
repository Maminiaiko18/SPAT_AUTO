CREATE OR REPLACE VIEW CHANTIERLIBELLE (
  ID,
  IDTRAVAUX,
  NOM,
  DATYDEBUT,
  DATYFIN,
  MONTANT,
  AVANCEMENT,
  IDTIERS,
  ETAT,
  TRAVAUX,
  TIERS,
  TIERSLIB,
  DIRTRAVAUX,
  CODEETABLISSEMENT,
  PROJET,
  CODEETABLISSEMENTLIB,
  PROJETLIB,
  ETATLIB
) AS
  SELECT
    CC.ID,
    CC.NOMTRAVAUX                                                     AS IDTRAVAUX,
    CC.NOM,
    CC.DATYDEBUT,
    CC.DATYFIN,
    CC.MONTANT,
    NVL ( (
      SELECT
        SUM(P.POURCENTAGE)
      FROM
        POURCENTAGEPROJET P
      WHERE
        P.IDCHANTIER = CC.ID
        AND P.ETAT >= 11
      GROUP BY
        IDCHANTIER
    ), 0) AVANCEMENT,
    CC.NOMTIERS AS IDTIERS,
    CC.ETAT,
    CC.IDTRAVAUX AS TRAVAUX,
    CC.TIERS,
    CC.TIERSLIB,
    DIR.ABBREVDIR AS DIRTRAVAUX,
    T.CODEETABLISSEMENT,
    T.PROJET,
    CE.VAL AS CODEETABLISSEMENTLIB,
    P.DESIGNATION AS PROJETLIB,
    CASE
      WHEN CC.ETAT =1 THEN
        'CREE'
      WHEN CC.ETAT=11 THEN
        'VISEE'
    END AS ETATLIB
  FROM
    CHANTIERLIBCOMPLET CC,
    TRAVAUX            T,
    CODEETABLISSEMENT  CE,
    DIRECTION          DIR,
    PROJET             P
  WHERE
    CC.IDTRAVAUX =T.ID(+)
    AND T.CODEETABLISSEMENT =CE.ID (+)
    AND CE.DESCE =DIR.IDDIR (+)
    AND T.PROJET =P.ID (+);