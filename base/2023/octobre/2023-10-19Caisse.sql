ALTER TABLE CAISSE ADD DEVISE VARCHAR(100) CONSTRAINT CAISSE_DEVISE_FK REFERENCES DEVISE(ID);

CREATE VIEW CAISSELIBELLE AS
  SELECT
    C.ID,
    C.VAL,
    C.DESCE,
    C.NUMERO,
    C.TYPE,
    C.RANGSITCPTCRT,
    C.PLACESITCPTCRT,
    C.DEVISE,
    D.VAL            AS DEVISELIB
  FROM
    CAISSE C,
    DEVISE D
  WHERE
    C.DEVISE =D.ID(+);

CREATE OR REPLACE VIEW REPORTLIB (
  ID,
  DATY,
  MONTANT,
  CAISSE,
  DEVISE,
  IDCAISSE,
  ETAT
) AS
  SELECT
    R.ID,
    R.DATY,
    R.MONTANT,
    C.VAL     AS CAISSE,
    R.DEVISE,
    C.ID      AS IDCAISSE,
    R.ETAT
  FROM
    REPORT R
    JOIN CAISSE C
    ON R.CAISSE = C.ID;

CREATE OR REPLACE VIEW REPORTLIB_ORDRE (
  ID,
  DATY,
  CAISSE,
  MONTANT,
  DEVISE,
  IDCAISSE,
  ETAT
) AS
  SELECT
    R.ID,
    R.DATY,
    C.VAL     AS CAISSE,
    R.MONTANT,
    R.DEVISE,
    C.ID      AS IDCAISSE,
    R.ETAT
  FROM
    REPORT R
    JOIN CAISSE C
    ON R.CAISSE = C.ID;