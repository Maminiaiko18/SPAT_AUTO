CREATE OR REPLACE  VIEW ORDONNERPAYEMENT_LIB_DEVISE (ID, DED_ID, IDLIGNE, DESTINATION, DATY, MONTANT, REMARQUE, ETAT, NUMEROOP, MODEPAIEMENT, TIERS, ADRESSE, NUMFACT, DESTINATIONLIB, BENEFICIAIRE, DEVISE, DEVISELIB, MONTANTDEVISE) AS 
  SELECT
	o.ID,o.DED_ID,o.IDLIGNE,o.DESTINATION,o.DATY,o.MONTANT,o.REMARQUE,o.ETAT,o.NUMEROOP,o.MODEPAIEMENT,o.TIERS,o.ADRESSE,o.NUMFACT,o.DESTINATIONLIB,o.BENEFICIAIRE,o.DEVISE,o.DEVISELIB,
	CAST (nvl(o.MONTANT /(SELECT MONTANT FROM COURSDEVISE d WHERE d.DATY = o.DATY AND d.IDDEVISE = o.DEVISE AND ESTMICTSL = 0 ), 0) AS NUMBER(30,2) ) AS MONTANTDEVISE
FROM
	OrdonnerPayement_LIB o;
	

