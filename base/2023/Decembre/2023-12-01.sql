CREATE OR REPLACE  VIEW DEM_ACHAT_MERELIB (ID, CODEETABLISSEMENT, PROJET, IDENGAGEMENT, DESIGNATION, NUM, DATY, CODEETABLISSEMENTLIB, IDENGAGEMENTLIB, PROJETLIB, ETAT, ETATLIB,IDCATEGORIEACHAT,IDCATEGORIEACHATlib) AS 
  SELECT 
dam.ID,dam.CODEETABLISSEMENT,dam.PROJET,dam.IDENGAGEMENT,dam.DESIGNATION,dam.NUM,dam.DATY , 
c.val AS codeetablissementlib , 
e.designation AS idengagementlib  , 
p.designation  AS projetlib ,
dam.etat,
CASE WHEN 
	dam.etat='1' THEN 'CREE'
	WHEN dam.ETAT='11' THEN 'VISEE'
END  AS etatlib,
dam.IDCATEGORIEACHAT,
catega.val AS IDCATEGORIEACHATlib
FROM dem_achat_mere dam LEFT JOIN codeetablissement c ON dam.codeetablissement = c.id 
LEFT JOIN engagement e ON e.id = dam.idengagement 
LEFT JOIN projet p ON p.id = dam.projet
LEFT JOIN categorieachat catega ON dam.IDCATEGORIEACHAT =catega.id;



CREATE OR REPLACE  VIEW DEM_ACHAT_MERELIB_CREE (ID, CODEETABLISSEMENT, PROJET, IDENGAGEMENT, DESIGNATION, NUM, DATY, CODEETABLISSEMENTLIB, IDENGAGEMENTLIB, PROJETLIB, ETAT, ETATLIB,IDCATEGORIEACHAT,IDCATEGORIEACHATlib) AS 
  SELECT ID,CODEETABLISSEMENT,PROJET,IDENGAGEMENT,DESIGNATION,NUM,DATY,CODEETABLISSEMENTLIB,IDENGAGEMENTLIB,PROJETLIB,ETAT,ETATLIB,IDCATEGORIEACHAT,IDCATEGORIEACHATlib FROM  DEM_ACHAT_MERELIB WHERE etat='1';

 
