  SELECT ID,CODEETABLISSEMENT,PROJET,IDENGAGEMENT,DESIGNATION,NUM,DATY,CODEETABLISSEMENTLIB,IDENGAGEMENTLIB,PROJETLIB,ETAT,ETATLIB,IDCATEGORIEACHAT,IDCATEGORIEACHATlib FROM  DEM_ACHAT_MERELIB WHERE etat='11';


