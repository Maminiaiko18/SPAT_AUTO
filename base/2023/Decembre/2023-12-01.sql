
CREATE  table categorieachat(
id varchar(100) constraint categorieachat_pk primary key,
val varchar (100),
desce varchar(100)
);
CREATE SEQUENCE SEQcategorieachat
      MINVALUE 1
      MAXVALUE 999999999999
      START WITH 1
      INCREMENT BY 1
      CACHE 20;

CREATE OR REPLACE FUNCTION GETSEQcategorieachat RETURN NUMBER IS
    RETOUR NUMBER;
BEGIN
    SELECT
        SEQcategorieachat.NEXTVAL INTO RETOUR
    FROM
        DUAL;
    RETURN RETOUR;
END;
