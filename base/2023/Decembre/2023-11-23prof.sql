CREATE OR REPLACE  VIEW NAVIREprofLIBCOMPLET (ID, REFERENCE, NOM, PAVILLON, JNT, JBT, PLT, LHT, LM, TE, VOLUME, REMARQUE, ETAT, TYPE, VALPAVILLON, DESCEPAVILLON, TYPENAVIRELIB, ARMATEUR, ARMATEURLIB) AS 
  SELECT nav.ID,
       nav.REFERENCE,
       nav.NOM,
       nav.PAVILLON,
       nav.JNT,
       nav.JBT,
       nav.PLT,
       nav.LHT,
       nav.LM,
       nav.TE,
       nav.VOLUME,
       nav.REMARQUE,
       nav.ETAT,
       nav.TYPE,
       p.val   AS valpavillon,
       p.DESCE AS descepavillon,
       tn.val  AS typenavirelib,
       nav.ARMATEUR,
       a.val   as ARMATEURLIB
FROM navire_prof nav
         left JOIN PAYS p ON p.id = nav.PAVILLON
         LEFT JOIN typenavire tn ON tn.id = nav.TYPE
         left join ARMATEUR_tbd a on a.ID = nav.ARMATEUR;







CREATE OR REPLACE  VIEW NAVIREprofLIB (ID, REFERENCE, NOM, PAVILLON, JNT, JBT, PLT, LHT, LM, TE, VOLUME, REMARQUE, ETAT, TYPE, ARMATEURLIB) AS 
  SELECT id,
       reference,
       nom,
       valpavillon   AS pavillon,
       JNT,
       JBT,
       PLT,
       LHT,
       LM,
       TE,
       lht * lm * te as volume,
       REMARQUE,
       etat,
       typenavirelib AS TYPE,
       ARMATEURLIB
FROM navireproflibcomplet;

