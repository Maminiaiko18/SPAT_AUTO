         CREATE OR REPLACE  VIEW CONTRATLIBCPLT as  select
        cont.ID,cont.IDTIERS, clt.NOM,cont.OBJET,cont.DATE_SIGNATURE,cont.DEBUT_CONTRAT,cont.FIN_CONTRAT,cont.DUREE,cont.UNITE,cont.TYPEDUREE,
        unite.VAL as valunite, unite.DESCE as desceunite,
        cont.ETAT,
        CASE
            WHEN cont.ETAT=1 THEN
                'CREE'
            WHEN cont.ETAT=11 THEN
                'VISE'
        END                   AS ETATLIB,
        cont.CODEETABLISSEMENT,
        cont.PROJET,
        cont.idlc,
        p.projet AS projetlib,
        ce.VAL AS CODEETABLISSEMENTlib,
        li.DESIGNATION AS lclib,
        cont.IDCHANTIER,
        ch.NOM  AS chantierlib,
        nvl(agc.montant,0) AS montant,
        av.id AS idavenant,
        CAST (nvl(ffc.montantpaye,0) AS NUMBER (30,2)) AS montantpaye
    from contrat cont
        LEFT join TIERS clt on clt.id = cont.IDTIERS
        LEFT join UNITE unite on cont.UNITE = unite.ID
        LEFT JOIN projet p ON  cont.PROJET =p.id
        LEFT JOIN codeetablissement ce ON cont.CODEETABLISSEMENT =ce.id
        LEFT JOIN lignecreditdepense li ON cont.IDLC =li.id 
        LEFT JOIN chantier ch ON cont.IDCHANTIER =ch.id
		LEFT JOIN avenantgrpcontrat agc ON cont.id=agc.idcontrat
		LEFT  JOIN avenant  av ON cont.id = av.IDCONTRAT AND av.RANG =0
        LEFT JOIN  facture_fournisseur_contratgrp ffc ON cont.id =ffc.idcontrat
		;
    
    
