CREATE OR REPLACE VIEW CHANTIER_LIB_NOM (
  ID,
  IDTRAVAUX,
  NOM,
  DATYDEBUT,
  DATYFIN,
  MONTANT,
  AVANCEMENT,
  NOMTIERS,
  IDTIERS,
  NOMTRAVAUX,
  ETAT,
  TIERS,
  TIERSLIB,
  DIRTRAVAUX,
  CODEETABLISSEMENT,
  PROJET,
  CODEETABLISSEMENTLIB,
  PROJETLIB
) AS
  SELECT
    CC.ID,
    CC.IDTRAVAUX,
    CC.NOM,
    DATYDEBUT,
    DATYFIN,
    CAST(CC.MONTANT AS NUMBER(30, 2)) AS MONTANT,
    NVL((
      SELECT
        MAX(POURCENTAGE)
      FROM
        POURCENTAGEPROJET P
      WHERE
        P.IDCHANTIER=CC.ID
      GROUP BY
        IDCHANTIER
    ), 0)AVANCEMENT,
    NOMTIERS,
    IDTIERS,
    NOMTRAVAUX,
    CC.ETAT,
    CC.TIERS,
    CC.TIERSLIB,
    DIR.ABBREVDIR AS DIRTRAVAUX,
    T.CODEETABLISSEMENT,
    T.PROJET,
    CE.VAL AS CODEETABLISSEMENTLIB,
    P.DESIGNATION AS PROJETLIB
  FROM
    CHANTIERLIBCOMPLET CC,
    TRAVAUX            T,
    CODEETABLISSEMENT  CE,
    DIRECTION          DIR,
    PROJET             P
  WHERE
    CC.IDTRAVAUX =T.ID(+)
    AND T.CODEETABLISSEMENT =CE.ID (+)
    AND CE.DESCE =DIR.IDDIR (+)
    AND T.PROJET =P.ID (+);

