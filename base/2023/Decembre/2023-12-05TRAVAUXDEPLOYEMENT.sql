CREATE OR REPLACE VIEW TRAVAUXLIBCOMPLET (
  ID,
  NOM,
  DATEDEBUT,
  DATEFIN,
  MONTANT,
  AVANCEMENT,
  DESCRIPTION,
  ETAT,
  IDTYPETRAVAUX,
  VALTYPETRAVAUX,
  DESCETYPETRAVAUX,
  VALDEVISE,
  DESCEDEVISE,
  PROJET,
  CODEETABLISSEMENT,
  PROJETLIB,
  CODEETABLISSEMENTLIB,
  TIERS,
  TIERSLIB
) AS
  SELECT
    T.ID,
    T.NOM,
    T.DATEDEBUT,
    T.DATEFIN,
    T.MONTANT,
    T.AVANCEMENT,
    T.DESCRIPTION,
    T.ETAT,
    T.IDTYPETRAVAUX,
    TYPET.VAL           AS VALTYPETRAVAUX,
    TYPET.DESCE         AS DESCETYPETRAVAUX,
    DEVISE.VAL          AS VALDEVISE,
    DEVISE.DESCE        AS DESCEDEVISE,
    T.PROJET,
    T.CODEETABLISSEMENT,
    P.DESIGNATION       AS PROJETLIB,
    C.VAL               AS CODEETABLISSEMENTLIB,
    T.TIERS,
    TIERS.NOM           AS TIERSLIB
  FROM
    TRAVAUX                     T
    JOIN TYPETRAVAUX TYPET
    ON T.IDTYPETRAVAUX = TYPET.ID JOIN DEVISEDEMAT DEVISE
    ON DEVISE.ID = T.IDDEVISE
    LEFT JOIN PROJET P
    ON T.PROJET = P.ID
    LEFT JOIN CODEETABLISSEMENT C
    ON T.CODEETABLISSEMENT =C.ID
    LEFT JOIN FOURNISSEUR_UNION_PERSONNEL TIERS
    ON T.TIERS=TIERS.ID;

