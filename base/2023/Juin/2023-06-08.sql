CREATE OR REPLACE  VIEW BORDEREAUFF_LIBCOMPLET (ID, DATY, NUMERO, DESIGNATION, ETAT, TIERS, TIERSLIB, MONTANTBUDGET, MONTANTAV, MONTANTAP,NUMFSB) AS 
  select br.ID,br.DATY,br.NUMERO,br.DESIGNATION,br.ETAT,br.TIERS,
           fup.NOM as tierslib,montantbudget, montantav, montantap,NUMFSB 
        from bordereauFF br
        left join FOURNISSEUR_UNION_PERSONNEL fup on fup.id=br.TIERS;

CREATE OR REPLACE  VIEW BORDEREAUFF_LIB_MONTANT (ID, DATY, NUMERO, DESIGNATION, ETAT, TIERS,NUMFSB, MONTANT, MONTANTBUDGET, MONTANTAV, MONTANTAP, PROJET, DIRECTION) AS 
  SELECT bf.ID,
       bf.DATY,
       bf.NUMERO,
       bf.DESIGNATION,
       bf.ETAT,
       bf.TIERSLIB  as TIERS,
       bf.numfsb,
       NVL(MO.MONTANT, 0) as montant,
       montantbudget,
       montantav,
       montantap,
       (SELECT PROJET  FROM liaisonbordereauFF_libcomplet WHERE IDBORDEREAU = bf.id AND ROWNUM = 1) AS PROJET,
       (SELECT DIRECTION  FROM liaisonbordereauFF_libcomplet WHERE IDBORDEREAU = bf.id AND ROWNUM = 1) AS DIRECTION 
FROM BORDEREAUFF_LIBCOMPLET BF 
         LEFT JOIN LIAISONBORDEREAUFF_SUM_MONTANT MO ON MO.IDBORDEREAU = BF.ID;

