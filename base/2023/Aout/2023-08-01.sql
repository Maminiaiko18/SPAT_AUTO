CREATE OR REPLACE
VIEW LIAISONENGAGEMENTFF_grp AS
SELECT
	LISTAGG(id, ';') WITHIN GROUP (
	ORDER BY id) AS idengagement,
	IDFACTUREFOURNISSEUR
FROM
	LIAISONENGAGEMENTFF
GROUP BY
	IDFACTUREFOURNISSEUR;

CREATE OR REPLACE
VIEW FFengagementpopup AS
SELECT
	fml.*,
	lg.idengagement AS idengaggrp
FROM
	FACTFOURN_MSUM_LIB fml
LEFT JOIN LIAISONENGAGEMENTFF_grp lg ON
	lg.IDFACTUREFOURNISSEUR = fml.id
WHERE
	fml.etat >= 11;

CREATE OR REPLACE
VIEW liaisonengagement_datefact AS
SELECT
	l.*,
	fml.daty
FROM
	liaisonengagement l
JOIN FACTFOURN_MSUM_LIB fml ON
	fml.id = l.id2;

CREATE VIEW liaisonengagement_RAP AS
SELECT
	id2,
	sum(nvl(montant, 0)) AS montant
FROM
	liaisonengagement
WHERE
	MONTANT <0
GROUP BY
	ID2;

