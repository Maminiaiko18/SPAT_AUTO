  SELECT 
e.ID,e.DESIGNATION,e.CODEETABLISSEMENT,e.PROJET,e.MONTANT,e.DISPOAVANT,e.DISPOAPRES,e.COMPTE,e.ETAT,e.CODEETABLISSEMENTLIB,e.PROJETLIB,e.IDLC,e.IDLCLIB,e.DATY,e.AVECFACTURE,e.AVECFACTURELIB,e.MONTANTOP,e.DISPONIBLE,e.TIERS,e.TIERSLIB,e.NUM,e.OBSERVATION,e.ANNEE,e.MONTANTRESTE,
case when l.ID2 like 'BC%'
then 
nvl(fbc.ID,l.ID2)
else 
l.ID2 
end AS idfacturefournisseur,
case when l.ID2 like 'BC%'
then 
nvl(fbc.MONTANT,l.MONTANT)
else 
l.montant 
end AS montantengager
FROM ENGAGEMENTLIB e
JOIN LIAISONENGAGEMENT l  ON  l.ID1 = e.ID
left join FACTFOURN_BC2 fbc on fbc.IDBC =l.ID2 
WHERE l.ETAT =11;



