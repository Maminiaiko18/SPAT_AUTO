CREATE OR REPLACE  VIEW FACTFOURN_BC as  SELECT 
-----maka ireo facture rattaché amin'BC
f.*
FROM FACTFOURN_MSUM_LIB f
JOIN AS_BONDELIVRAISON AB ON AB.ID= F.IDBL 
JOIN AS_BONDECOMMANDE ab2 ON AB2.ID= AB.ID_BC
WHERE f.ETAT >=11;


 CREATE OR REPLACE  VIEW FACTFOURN_BC_GRP (MONTANT, ID) AS 
  SELECT 
------groupena par idbc ny montantff ao amin ny FACTFOURN_BC
SUM(montant) AS montant,
idbc AS id  
FROM FACTFOURN_BC GROUP BY IDBC;


CREATE OR REPLACE  VIEW LIAISONENGAGEMENT_grpid2 (ID2, MONTANT) AS 
-------groupena par  id2 (idbc na par idff) ny liaisonengagement
  SELECT id2, sum(nvl(montant,0)) AS montant  FROM liaisonengagement  group BY ID2;

CREATE VIEW BCrestengag AS 
---------------ijerena montantreste(reste anah engagement an'BC rehefa nanalan'ny FF)
SELECT f.ID  AS idbc , (l.montant -f.MONTANT) AS MONTANTreste FROM FACTFOURN_BC_GRP f JOIN LIAISONENGAGEMENT_grpid2 l ON f.id= l.id2;



