JOIN avoirfc a ON a.ID = a2.IDMERE 
JOIN FACTURE_CLIENT_FILLE fcf ON a2.IDDETAILFACTURE = fcf.ID 
JOIN FACTURECLIENT FC ON FCF.IDMERE = FC.ID
JOIN AVOIRFCAVECTAUX a3 ON a3.ID = a2.ID ;


