CREATE OR REPLACE  VIEW COMPTECA_COMPLET (ID, VAL, DESCE, LIBELLE) AS 
  SELECT ca.id
  , ca.val
  , ca.desce
  , ca.LIBELLE||' '||me.VAL ||' VAOVAO' AS LIBELLE  
  FROM compteca ca
  LEFT JOIN mereca me ON me.id = ca.DESCE 
  UNION ALL
  SELECT 
  cad.ID
  ,cad.VAL
  ,cad.DESCE
  ,cad.LIBELLE||' '||mea.val || ' ANCIEN' AS LIBELLE 
  FROM comptecadetails cad
LEFT JOIN mereca_ancien mea ON mea.id = cad.DESCE 
