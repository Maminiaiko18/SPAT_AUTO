SELECT 
	a2.ID AS idAvoirFille,
	a2.IDMERE AS id ,
	a.CODE AS codeAvoir,
	a.DATY AS DatyAvoirFC,
	CASE WHEN a.TYPE = 1 THEN 'interne'
	WHEN a.TYPE = 2 THEN 'externe' END AS TYPE ,
	a.IDFACTURE AS idFC,
	FC.CODE AS codeFC,
	FC.daty AS datyFC,
	FC.NOMCLT AS client,
	FCF.DESIGNATION,
	a2.PU,QTE,
	a2.DUREE,
	FCF.COMPTE, 
	a2.REMISE,
	a2.tva,
	a2.REDUCTION,
	a2.MAJORATION,
	a3.DEVISE,
	a3.TAUX,
	a3.MONTANT AS montantHTDevise,
	a3.MONTANTAVECTSAUX AS MTTHTVA,
	a3.MONTANTTVA,
	a3.MONTANTTTC,
	CASE EXTRACT (MONTH FROM a.DATY) 
		WHEN 1 THEN 'janvier'
		WHEN 2 THEN 'fevrier'
		WHEN 3 THEN 'mars'
		WHEN 4 THEN 'avril'
		WHEN 5 THEN 'mai'
		WHEN 6 THEN 'juin'
		WHEN 7 THEN 'juillet'
