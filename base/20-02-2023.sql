CREATE OR REPLACE VIEW AS_BONDECOMMANDE_FILLEMTT (ID,
PRODUIT,
IDBC,
QUANTITE,
PU,
QUANTITEPARPACK,
MONTANT,
REMARQUE,
UNITE,
TVA,
DESIGNATION,
REMISE,
OBSERVATION,
DEVISE,
TAUX,
MONTANTHT) AS
SELECT
	bcf.ID,
	bcf.PRODUIT,
	bcf.IDBC,
	bcf.QUANTITE,
	bcf.PU,
	bcf.QUANTITEPARPACK,
	bcf.MONTANT,
	bcf.REMARQUE,
	bcf.UNITE,
	bcf.TVA,
	bcf.DESIGNATION,
	bcf.REMISE,
	bcf.OBSERVATION,
	bcf.DEVISE,
	bcf.TAUX,
	((QUANTITE pu) - (QUANTITE pu)*REMISE /100) AS montantht
FROM
	AS_BONDECOMMANDE_FILLE bcf
;