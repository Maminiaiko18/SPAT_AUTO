CREATE OR REPLACE VIEW "PLACEMENT_ANNULATION" ("ID", "ENTITE", "DATE_PLACEMENT", "DATE_ECHEANCE", "DUREE", "MONTANT", "TAUX", "NUMERO", "BANQUE", "ETAT", "IDDEVISE", "MONTANTDEVISE") AS 
  SELECT 
    "ID",
    "ENTITE",
    "DATE_PLACEMENT",
    "DATE_ECHEANCE",
    "DUREE",
    "MONTANT",
    "TAUX",
    "NUMERO",
    "BANQUE",
    "ETAT",
    "IDDEVISE",
    "MONTANTDEVISE" 
  FROM
PLACEMENTLIB_ECHU e where id not in (SELECT ancienplacement FROM PLACEMENTLIBCOMPLET a where etat>=11 AND e.id=a.ancienplacement);