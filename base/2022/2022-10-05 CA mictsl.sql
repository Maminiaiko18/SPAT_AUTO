CREATE OR REPLACE VIEW "COMPTECAFACTUREM1" ("ID", "VAL", "DESCE", "IDMERE", "DESIGNATION", "QUANTITE", "PU", "IDPRODUIT", "DEVISE", "TAUX", "QTELIVREE", "RESTEALIVRER", "MONTANTTAUX", "MONTANT", "MONTANTAVOIRSANSTAUX", "MONTANTAVOIRAVECTAUX", "TVA", "IDACTIVITE", "ACTIVITELIB", "HEUREDEBUT", "HEUREFIN", "MOISLIB", "TAUXEURO", "MONTANTHTEURO", "MONTANTTVAEURO", "MONTANTTAXE", "MAJORATION", "REDUCTION", "DATEFACT", "RUBRIQUE", "RANG", "DATY", "VALMERECA", "DESCEMERECA", "MOIS", "ANNEE", "COMPTE", "TYPE", "MERECA","TIERS","MOISM1","ANNEEM1") AS 
  select fdc.ID,
       cca.VAL,
       cca.DESCE,
       IDMERE,
       DESIGNATION,
       QUANTITE,
       PU,
       IDPRODUIT,
       DEVISE,
       TAUX,
       cast(0 as NUMBER(10, 2))     as QTELIVREE,
       cast(0 as NUMBER(10, 2))     as RESTEALIVRER,
       MONTANT                      as MONTANTTAUX,
       MONTANT,
       MTAVOIR                      as MONTANTAVOIRSANSTAUX,
       MTAVOIR                      as MONTANTAVOIRAVECTAUX,
       TVA,
       IDACTIVITE,
       cast('-' as VARCHAR2(100))      ACTIVITELIB,
       HEUREDEBUT,
       HEUREFIN,
       MOISLIB,
       cast(0 as NUMBER(10,3)) as TAUXEURO,
       cast(0 as NUMBER(10,3)) as MONTANTHTEURO,
       cast(0 as NUMBER(10,3)) as MONTANTTVAEURO,
       MONTANTTVA                   as MONTANTTAXE,
       MAJORATION,
       REDUCTION,
       DATEFACT,
       RUBRIQUE,
       RANG,
       DATY,
       mca.val                      as valMereCA,
       mca.desce                    as desceMereCA,
       extract(month from fdc.daty) as mois,
       extract(year from fdc.daty)  as annee,
       fdc.compte,
       TYPE,
       cca.DESCE                    as mereca,
       fdc.tiers,
       CASE WHEN extract(month from fdc.daty)=1 THEN 12
       		ELSE extract(month from fdc.daty)-1 END as moisM1,
       extract(year from fdc.daty)-1 AS anneeM1
from CompteCA cca,
     MereCA mca,
     CAFCFILLECOMPLET fdc
where fdc.compte like cca.val || '%'
  and fdc.compte is not null
  and cca.desce = mca.id;
 
 CREATE OR REPLACE VIEW "COMPTECAFACTURE" 
 ("ID", "VAL", "DESCE", "IDMERE", "DESIGNATION", "QUANTITE", "PU", "IDPRODUIT", "DEVISE", "TAUX", "QTELIVREE", "RESTEALIVRER", 
 "MONTANTTAUX", "MONTANT", "MONTANTAVOIRSANSTAUX", "MONTANTAVOIRAVECTAUX", "TVA", "IDACTIVITE", "ACTIVITELIB",
 "HEUREDEBUT", "HEUREFIN", "MOISLIB", "TAUXEURO", "MONTANTHTEURO", "MONTANTTVAEURO", "MONTANTTAXE", "MAJORATION", 
 "REDUCTION", "DATEFACT", "RUBRIQUE", "RANG", "DATY", "VALMERECA", "DESCEMERECA", "MOIS", "ANNEE", "COMPTE", "TYPE", "MERECA") AS 
  select ID,
       VAL,
       DESCE,
       IDMERE,
       DESIGNATION,
       QUANTITE,
       PU,
       IDPRODUIT,
       DEVISE,
       TAUX,
       QTELIVREE,
       RESTEALIVRER,
       MONTANTTAUX,
       MONTANT,
       MONTANTAVOIRSANSTAUX,
       MONTANTAVOIRAVECTAUX,
       TVA,
       IDACTIVITE,
       ACTIVITELIB,
       HEUREDEBUT,
       HEUREFIN,
       MOISLIB,
       TAUXEURO,
       MONTANTHTEURO,
       MONTANTTVAEURO,
       MONTANTTAXE,
       MAJORATION,
       REDUCTION,
       DATEFACT,
       RUBRIQUE,
       RANG,
       DATY,
       valMereCA,
       desceMereCA,
       CASE WHEN ccf.tiers='0120037' OR ccf.tiers='clt1' THEN ccf.moisM1 
       ELSE ccf.mois END AS mois,
       CASE WHEN (ccf.tiers='0120037' OR ccf.tiers='clt1') AND ccf.moisM1=12 THEN ccf.anneeM1 
       ELSE annee END AS annee,
       compte,
       TYPE,
       mereca
from COMPTECAFACTUREM1 ccf;