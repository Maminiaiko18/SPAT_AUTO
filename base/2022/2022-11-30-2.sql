CREATE OR REPLACE  VIEW FOURNISSEUR_UNION_PERSONNEL AS  SELECT tp.ID,
       tp.NOM,
       tp.DESCRIPTION,
       tp.NIF,
       tp.STAT,
       tp.CONTACT,
       '' as responsable,
       tp.ADRESSE,
       tp.TYPE,
       tp.ETAT,
       tp.COMPTEAUXFOURNISSEUR,
       tp.COMPTEAUXCLIENT,
       '' as cdclt
FROM TIERS_LIB tp
UNION
SELECT an.SA_COMPTEURNUMERO       AS ID,
       an.NOM || ' ' || an.PRENOM AS nom,
       ''                         AS DESCRIPTION,
       ''                         AS NIF,
       ''                         AS STAT,
       an.TELEPHONE               AS CONTACT,
       ''                         AS RESPONSABLE,
       an.RUE1                    AS ADRESSE,
       '' as type,
       11                         AS etat,
       ''                         as COMPTEAUXFOURNISSEUR,
       ''                         as COMPTEAUXCLIENT,
       '' as cdclt
FROM ANALYSEPERSONNELUNION an

union
select cl.cdclt    as ID,
       cl.nomclt   as nom,
       ''          AS DESCRIPTION,
       cl.nif      AS NIF,
       cl.nmsttclt AS STAT,
       cl.telclt   AS CONTACT,
       ''          AS RESPONSABLE,
       cl.adrclt   AS ADRESSE,
       cl.cdcat    as TYPE,
       11          AS etat,
       ''          as COMPTEAUXFOURNISSEUR,
       ''          as COMPTEAUXCLIENT,
       cl.cdclt
from V_CLIENT_CATEGORIE cl;


