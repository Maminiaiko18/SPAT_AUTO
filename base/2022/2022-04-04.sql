create or replace view NUMEROPIECE as
select to_date(ID,'dd-mm-yyyy') as daty,
       cast( VAL as number(10)) -1  as numeroactuelle,
       cast(val as number(10))numerosuivant,
       cast(extract(month from to_date(id, 'dd-mm-yyyy')) as NUMBER(10)) as mois,
       cast(extract(year from to_date(id, 'dd-mm-yyyy')) as NUMBER(10)) as annee,
       type,
       modepaiement
       from NUMEROJOURNAL_SEQUENCE
/

CREATE OR REPLACE  VIEW PROFORMAMSUM (ID, DATY, TIERS, DESIGNATION, TYPE, TVA, REMARQUE, IDUSER,
DATE_ECHEANCE, ETAT, IDPREVISION, MONTANT, MONTANTTVA, MONTANTAVOIR, MONTANTTTC, ESCALE, 
TYPELIB, IDCATEGORIE, CATEGORIELIB, IDPROVISION, IDPROVISIONLIB, ESTDDPMICTSL, DEVISEMERE, 
CODEPRESTATION, CODEPRESTATIONLIB, CODE, ESTMICTSL, CODEPROVISION, MONTANTTTCVRAI, NAVIRE, 
ARMATEURLIB, EXERCICE, IDAVOIR, POURCOMPTE, POURCOMPTELIB, PROVENANCE, DESTINATION , 
DATEDEPART , DATEARRIVEE , HEUREDEPART , HEUREARRIVEE , BATEAU , BATEAULIB) AS 
  SELECT fc.ID,
          fc.DATY,
          fc.TIERS,
          fc.DESIGNATION,
          fc.TYPE,
          fc.TVA,
          fc.REMARQUE,
          fc.IDUSER,
          fc.DATE_ECHEANCE,
          fc.ETAT,
          fc.idprevision,
          CAST (NVL (grp.montant, 0) AS NUMBER (30, 3)) AS montant, --montanttaux
          CAST (NVL (grp.MONTANTTVA, 0) AS NUMBER (30, 3)) AS montanttva,
          CAST (NVL (grp.MONTANTAVOIRAVECTSAUX, 0) AS NUMBER (32, 3)) AS montantavoir,
          CAST (NVL (MONTANTTTC, 0)-NVL (grp.MONTANTAVOIRAVECTSAUX, 0) AS NUMBER (30, 3)) AS MONTANTTTC,
          pr.ESCALE,
          tfc.VAL AS typelib,
          fc.IDCATEGORIE,
          catfc.VAL AS CATEGORIELIB,
          fc.IDPROVISION,
          fcf.DESIGNATION AS IDPROVISIONlib,
          fc.ESTDDPMICTSL,
          fc.DEVISEMERE,
          fc.codePrestation,
          cp.VAL AS codePrestationlib,
          fc.code,
          fc.ESTMICTSL,
          fcf.CODE AS codeprovision,
          CAST (
             NVL (NVL (grp.MONTANTTVA, 0) + grp.MONTANT, 0) AS NUMBER (30, 3))
             AS MONTANTTTCVRAI,
          pr.NAVIRE,
          nv.armateurlib,
          fc.exercice,
          fc.IDAVOIR,
          fc.pourcompte,
          fup.NOM as pourcomptelib , 
          fc.provenance , 
          fc.destination , 
          fc.DATEDEPART , 
          fc.DATEARRIVEE , 
          fc.HEUREDEPART , 
          fc.HEUREARRIVEE , 
          fc.BATEAU , 
          n.nom AS bateaulib 
          
     FROM PROFORMA_MERE fc
          LEFT JOIN proforma_fille_lib grp ON grp.idmere = fc.id
          LEFT JOIN PREVISION pr ON pr.id = fc.IDPREVISION
          LEFT JOIN TYPEFC tfc ON tfc.ID = fc.TYPE
          LEFT JOIN CATEGORIEFC catfc ON catfc.ID = fc.IDCATEGORIE
          LEFT JOIN PROFORMA_MERE fcf ON fcf.id = fc.IDPROVISION
          LEFT JOIN CODE_PRESTATION cp ON fc.codePrestation = cp.id
          LEFT JOIN NAVIRELIBCOMPLET nv ON pr.NAVIRE = nv.id
          left join FOURNISSEUR_UNION_PERSONNEL fup on fup.ID=fc.POURCOMPTE
         LEFT JOIN NAVIRE n ON n.id = fc.BATEAU ;





