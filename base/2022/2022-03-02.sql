from engagement_fille ef
    left join PAYEMENTENGAGEMENT pe on pe.IDENGAGEMENT=ef.ID
group by ef.MONTANT,ef.DESIGNATION,ef.id,ef.IDMERE,pe.IDENGAGEMENT;


