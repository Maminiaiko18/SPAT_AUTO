CREATE OR REPLACE  VIEW FACTURE_FOURNISSEUR_TRAVAUX (ID, DATY, TIERSLIB, NUMEROOP, CODE, PROJETLIB, CODE_ETABLISSEMENTLIB, NATURELIB, DESIGNATION, EXERCICE, DATE_ECHEANCE, MONTANTTTCVRAI, MONTANTAVOIR, MONTANTTTC, MONTANTPAYE, MONTANTRESTE, NUMOP, ETATLIB, MONTANT, IDCONTRAT, CR, PREVALIDATION, IDCHANTIER, IDTRAVAUX, NOMTRAVAUX, NOMCHANTIER, DUREECONTRAT, UNITELIB, PREVALIDATIONLIB, DATEREGUL, MODEPAIEMENT, DATEFACTURE, NUMBC, NUMBED, NUMFSB) AS 
  SELECT
	FT.ID,
        FT.DATY,
        FT.TIERSLIB,
        FT. NUMEROOP,
        FT. CODE,
        FT. PROJETLIB,
        FT. CODE_ETABLISSEMENTLIB,
        FT. NATURELIB,
        FT.DESIGNATION,
        FT.EXERCICE,
        FT.DATE_ECHEANCE,
        CAST (FT. MONTANTTTCVRAI AS NUMBER(38,2)) ,
        CAST (FT. MONTANTAVOIR AS NUMBER(38,2)) ,
        CAST (FT. MONTANTTTC AS NUMBER(38,2)) ,
        CAST (FT. MONTANTPAYE AS NUMBER(38,2)) ,
        CAST (FT.MONTANTRESTE AS NUMBER(38,2)) ,
        FT.NUMOP,
        FT. ETATLIB,
        CAST (FT.MONTANT AS NUMBER(38,2)) ,
	FT.idcontrat,
	FT.cr,
	 CAST (FT.PREVALIDATION AS NUMBER(10,0)) ,
	c.IDCHANTIER ,
	c.idtravaux,
	c.nomtravaux,
	c.nomchantier,
	c.dureecontrat,
	c.unitelib,
	PREVALIDATIONlib,
	dateregul,
	modepaiement,
	 FT.DATEFACTURE,
	FT.NUMBC,
	FT.NUMBED,
	FT.NUMFSB
FROM
	facture_fournisseur_contrat FT
JOIN contratchantiertravaux c ON
	FT.idcontrat = c.id
	ORDER BY FT.DATY ASC;