CREATE SEQUENCE seqparamcrypt
  MINVALUE 1
  MAXVALUE 999999999999999999999999999
  START WITH 10
  INCREMENT BY 1
  CACHE 20;

create or replace FUNCTION GETSEQPARAMCRYPT
  RETURN NUMBER IS
  retour NUMBER;
BEGIN
  SELECT seqparamcrypt.nextval INTO retour FROM dual;
  return retour;
END;


