CREATE OR REPLACE FORCE VIEW PROVISIONFACTUREDEFINITIVE
(
   ID,
   DATY,
   TIERS,
   DESIGNATION,
   TYPE,
   TVA,
   REMARQUE,
   IDUSER,
   DATE_ECHEANCE,
   ETAT,
   MONTANT,
   MONTANTTVA,
   MONTANTAVOIR,
   MONTANTTTC,
   MONTANTPAYE,
   MONTANTRESTE,
   TIERSLIB,
   CONTACT,
   ADRESSE,
   IDPREVISION,
   ESCALE,
   ETATLIB,
   TYPELIB,
   IDCATEGORIE,
   CATEGORIELIB,
   IDPROVISION,
   IDPROVISIONLIB
)
AS
   SELECT "ID",
          "DATY",
          "TIERS",
          "DESIGNATION",
          "TYPE",
          "TVA",
          "REMARQUE",
          "IDUSER",
          "DATE_ECHEANCE",
          "ETAT",
          cast(MONTANT as number(32,3)) as MONTANT,
          cast(MONTANTTVA as number(32,3)) as montanttva,
          cast(MONTANTAVOIR as number(32,3)) as MONTANTAVOIR,
          cast(MONTANTTTC as number(32,3)) as MONTANTTTC,
          cast(MONTANTPAYE as number(32,3)) as MONTANTPAYE,
          cast(MONTANTRESTE as number(32,3)) as MONTANTRESTE,
          "TIERSLIB",
          "CONTACT",
          "ADRESSE",
          "IDPREVISION",
          "ESCALE",
          "ETATLIB",
          "TYPELIB",
          "IDCATEGORIE",
          "CATEGORIELIB",
          "IDPROVISION",
          "IDPROVISIONLIB"
     FROM facture_client_union
    WHERE     idcategorie = 'CATFCO2'
          AND id IN (SELECT idProvision
                       FROM factureclient
                      WHERE etat >= 11)
          AND etat >= 11;
		  
