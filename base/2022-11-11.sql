
 CREATE OR REPLACE  VIEW FACTURECLIENTENALERTE AS
select v.*
  from  FACTURE_CLIENT_UNIONV v where (CAST((v.DATE_ECHEANCE-to_date(CURRENT_DATE)) AS integer))<=10 AND (CAST((v.DATE_ECHEANCE-to_date(CURRENT_DATE)) AS integer)) >=0 AND MONTANTRESTE>0;
  
 
 
CREATE OR REPLACE
VIEW FACTURECLIENTENRETARD  AS 
  SELECT
	FACTURE_CLIENT_UNIONV.*
FROM
	FACTURE_CLIENT_UNIONV
WHERE
	DATE_ECHEANCE< to_date(CURRENT_DATE) AND MONTANTRESTE>0
;





